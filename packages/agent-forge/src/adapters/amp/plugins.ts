// ---- hooks -------------------------------------------------------------

function generateHooksPlugin(hooks: readonly Hook[]): string {
  const lines = [
    '// AUTO-GENERATED by agent-forge; do not edit by hand.',
    '// Source of truth: ./agent-forge-hooks.yaml',
    "import { spawnSync } from 'node:child_process';",
    '',
    'function runHook(command, payload) {',
    "  spawnSync('sh', ['-c', command], {",
    '    input: JSON.stringify(payload),',
    "    stdio: ['pipe', 'inherit', 'inherit'],",
    '  });',
    '}',
    '',
    'export default function (amp) {',
  ];

  const byEvent = new Map<string, Hook[]>();
  for (const hook of hooks) {
    for (const e of hook.events) {
      const native = canonicalToAmp[e];
      if (!native) continue;
      const list = byEvent.get(native) ?? [];
      list.push(hook);
      byEvent.set(native, list);
    }
  }

  for (const [nativeEvent, list] of byEvent) {
    lines.push(`  amp.on(${JSON.stringify(nativeEvent)}, (payload) => {`);
    for (const hook of list) {
      const meta = JSON.stringify({
        id: hook.id,
        canonicalEvent: hook.events[0],
      });
      lines.push(
        `    runHook(${JSON.stringify(hook.command)}, { ...payload, _agentForge: ${meta} });`,
      );
    }
    lines.push('  });');
  }

  lines.push('}');
  return lines.join('\n');
}

export async function writeAmpHooks(
  ir: IR,
  scope: Scope,
  cwd: string,
  opts: WriteOpts = {},
): Promise<WriteReport> {
  const hooks = ir.hooks ?? [];
  if (hooks.length === 0) return { written: [], skipped: [], warnings: [] };

  const warnings: string[] = [];
  const skipped: { path: string; reason: string }[] = [];
  const compatible: Hook[] = [];
  for (const hook of hooks) {
    const unmapped = hook.events.filter((e) => !canonicalToAmp[e]);
    if (unmapped.length === hook.events.length) {
      warnings.push(
        `hook '${hook.id ?? '?'}': no amp.on() equivalent for events ${unmapped.join(',')} [AM2][AM7]`,
      );
      skipped.push({
        path: `hooks/${hook.id ?? '?'}.yaml`,
        reason: `no amp mapping for events: ${unmapped.join(',')}`,
      });
      continue;
    }
    if (unmapped.length > 0) {
      warnings.push(
        `hook '${hook.id ?? '?'}': partial mapping; events ${unmapped.join(',')} dropped [AM2][AM7]`,
      );
    }
    if (hook.matcher) {
      warnings.push(
        `hook '${hook.id ?? '?'}': matcher '${hook.matcher}' has no verified amp.on() payload-matching field (dropped) [AM2]`,
      );
    }
    compatible.push(hook);
  }

  const p = paths(scope, cwd);
  if (compatible.length > 0) {
    if (!opts.dryRun) {
      await mkdir(p.pluginsDir, { recursive: true });
      await writeFile(
        p.hooksPluginFile,
        generateHooksPlugin(compatible),
        'utf8',
      );
      await writeFile(
        p.hooksManifestFile,
        dump({ hooks: compatible }, { lineWidth: 100, noRefs: true }),
        'utf8',
      );
    }
    return {
      written: [p.hooksPluginFile, p.hooksManifestFile],
      skipped,
      warnings,
    };
  }
  return { written: [], skipped, warnings };
}

export async function readAmpHooks(
  scope: Scope,
  cwd: string,
): Promise<Hook[] | undefined> {
  const p = paths(scope, cwd);
  if (!existsSync(p.hooksManifestFile)) return undefined;
  const text = await readFile(p.hooksManifestFile, 'utf8');
  const parsed = (load(text) ?? {}) as { hooks?: Hook[] };
  return parsed.hooks?.length ? parsed.hooks : undefined;
}
