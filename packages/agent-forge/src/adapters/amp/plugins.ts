import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dump, load } from 'js-yaml';
import type {
  Agent,
  Command,
  Hook,
  IR,
  Scope,
  WriteOpts,
  WriteReport,
} from '../../core/index.js';
import { canonicalToAmp } from './events.js';
import { paths } from './paths.js';

/**
 * Delivery for agents/commands/hooks: Amp has no file-config surface for any
 * of the three (agents = built-ins + `amp.createAgent()`; commands folded
 * into the Plugin API's `registerCommand`; legacy `amp.hooks` retired for
 * `on()` registrations) — capability `plugin` for all three [AM1][AM2][AM3]
 * [AM9]. Each emitter writes a generated Bun-run `.ts` file (the artifact
 * Amp actually loads) plus a YAML sidecar (our source of truth on re-read,
 * same two-file split as the opencode hooks precedent).
 */

// ---- agents ---------------------------------------------------------------

/** IR agent fields `amp.createAgent()` has no documented parameter for —
 * only `name` + the system prompt (`body`) are mapped [AM1][AM9]; every
 * other field is a named, per-agent drop, never silently fabricated in. */
const AGENT_UNMAPPED_FIELDS = [
  'description',
  'model',
  'tools',
  'color',
  'permission_mode',
  'max_turns',
  'temperature',
  'mode',
  'memory',
] as const;

function generateAgentsPlugin(agents: readonly Agent[]): string {
  const lines = [
    '// AUTO-GENERATED by agent-forge; do not edit by hand.',
    '// Source of truth: ./agent-forge-agents.yaml',
    '',
    'export default function (amp) {',
  ];
  for (const agent of agents) {
    lines.push('  amp.createAgent({');
    lines.push(`    name: ${JSON.stringify(agent.name)},`);
    lines.push(`    prompt: ${JSON.stringify(agent.body)},`);
    lines.push('  });');
  }
  lines.push('}');
  return lines.join('\n');
}

export async function writeAmpAgents(
  ir: IR,
  scope: Scope,
  cwd: string,
  opts: WriteOpts = {},
): Promise<WriteReport> {
  const agents = ir.agents ?? [];
  if (agents.length === 0) return { written: [], skipped: [], warnings: [] };

  const warnings: string[] = [];
  for (const agent of agents) {
    for (const field of AGENT_UNMAPPED_FIELDS) {
      if ((agent as unknown as Record<string, unknown>)[field] !== undefined) {
        warnings.push(
          `agents/${agent.name}: '${field}' has no amp.createAgent() field mapping (dropped) [AM2][AM9]`,
        );
      }
    }
  }

  const p = paths(scope, cwd);
  if (!opts.dryRun) {
    await mkdir(p.pluginsDir, { recursive: true });
    await writeFile(p.agentsPluginFile, generateAgentsPlugin(agents), 'utf8');
    await writeFile(
      p.agentsManifestFile,
      dump({ agents }, { lineWidth: 100, noRefs: true }),
      'utf8',
    );
  }
  return {
    written: [p.agentsPluginFile, p.agentsManifestFile],
    skipped: [],
    warnings,
  };
}

export async function readAmpAgents(
  scope: Scope,
  cwd: string,
): Promise<Agent[] | undefined> {
  const p = paths(scope, cwd);
  if (!existsSync(p.agentsManifestFile)) return undefined;
  const text = await readFile(p.agentsManifestFile, 'utf8');
  const parsed = (load(text) ?? {}) as { agents?: Agent[] };
  return parsed.agents?.length ? parsed.agents : undefined;
}

